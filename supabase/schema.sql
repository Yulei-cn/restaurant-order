-- The only supported path for recording a cashier payment or refund. It locks the
-- order row, appends one immutable fiscal event, and records an audit entry atomically.
create or replace function public.record_payment_event(payment_payload jsonb)
returns table (
  payment_event_id uuid,
  payment_status text,
  paid_amount numeric
)
language plpgsql
as $$
declare
  target_order_id uuid := (payment_payload->>'order_id')::uuid;
  target_event_type text := payment_payload->>'event_type';
  target_method text := payment_payload->>'payment_method';
  target_amount numeric := (payment_payload->>'amount')::numeric;
  target_actor text := payment_payload->>'recorded_by';
  order_total numeric;
  prior_paid numeric;
  resulting_paid numeric;
  resulting_status text;
  created_event public.payment_events%rowtype;
begin
  if target_event_type not in ('payment', 'refund', 'void')
    or target_method not in ('cash', 'card', 'meal_voucher', 'other')
    or target_amount is null or target_amount <= 0
    or target_actor is null or btrim(target_actor) = '' then
    raise exception 'Invalid payment event';
  end if;

  select total_amount into order_total
  from public.orders where id = target_order_id for update;
  if not found then
    raise exception 'Order not found';
  end if;

  select coalesce(sum(case when event_type = 'payment' then amount else -amount end), 0)
  into prior_paid from public.payment_events where order_id = target_order_id;

  if target_event_type = 'payment' then
    if prior_paid + target_amount > order_total then
      raise exception 'Payment exceeds order total';
    end if;
    resulting_paid := prior_paid + target_amount;
  else
    if target_amount > prior_paid then
      raise exception 'Refund exceeds recorded payments';
    end if;
    resulting_paid := prior_paid - target_amount;
  end if;

  insert into public.payment_events (
    order_id, event_type, payment_method, amount, currency, terminal_reference,
    reason, recorded_by
  ) values (
    target_order_id, target_event_type, target_method, target_amount,
    coalesce(payment_payload->>'currency', 'EUR'),
    nullif(payment_payload->>'terminal_reference', ''),
    nullif(payment_payload->>'reason', ''), target_actor
  ) returning * into created_event;

  resulting_status := case
    when resulting_paid = order_total then 'paid'
    when resulting_paid = 0 and target_event_type in ('refund', 'void') then 'refunded'
    when resulting_paid > 0 then 'partial'
    else 'unpaid'
  end;

  update public.orders set payment_status = resulting_status where id = target_order_id;
  insert into public.cashier_audit_logs (event_type, entity_type, entity_id, actor, details)
  values (
    target_event_type, 'payment_event', created_event.id, target_actor,
    jsonb_build_object('order_id', target_order_id, 'amount', target_amount,
      'payment_method', target_method, 'fiscal_sequence', created_event.fiscal_sequence)
  );

  return query select created_event.id, resulting_status, resulting_paid;
end;
$$;

create or replace function public.close_cash_register_day(close_payload jsonb)
returns table (business_date date, expected_cash numeric, counted_cash numeric, variance_cash numeric)
language plpgsql
as $$
declare
  target_date date := coalesce((close_payload->>'business_date')::date, current_date);
  target_counted numeric := (close_payload->>'counted_cash')::numeric;
  target_actor text := close_payload->>'closed_by';
  calculated_cash numeric;
begin
  if target_counted is null or target_counted < 0 or target_actor is null or btrim(target_actor) = '' then
    raise exception 'Invalid daily closure';
  end if;

  select coalesce(sum(case when event_type = 'payment' and payment_method = 'cash' then amount
                           when event_type in ('refund', 'void') and payment_method = 'cash' then -amount else 0 end), 0)
  into calculated_cash
  from public.payment_events
  where recorded_at::date = target_date;

  insert into public.cash_register_days (business_date, opening_cash, opened_by)
  values (target_date, 0, target_actor)
  on conflict on constraint cash_register_days_pkey do nothing;

  update public.cash_register_days as cash_day
  set status = 'closed', expected_cash = opening_cash + calculated_cash,
      counted_cash = target_counted, variance_cash = target_counted - (opening_cash + calculated_cash),
      closed_by = target_actor, closed_at = timezone('utc', now()),
      closing_hash = encode(digest(concat_ws('|', target_date::text, calculated_cash::text, target_counted::text, target_actor), 'sha256'), 'hex')
  where cash_day.business_date = target_date and cash_day.status = 'open'
  returning cash_day.expected_cash, cash_day.counted_cash, cash_day.variance_cash
  into expected_cash, counted_cash, variance_cash;

  if not found then raise exception 'Business day is already closed'; end if;
  insert into public.cashier_audit_logs (event_type, entity_type, actor, details)
  values ('daily_close', 'cash_register_day', target_actor, jsonb_build_object('business_date', target_date, 'expected_cash', expected_cash, 'counted_cash', counted_cash, 'variance_cash', variance_cash));
  business_date := target_date;
  return next;
end;
$$;

create or replace function public.open_cash_register_day(open_payload jsonb)
returns table (business_date date, opening_cash numeric)
language plpgsql
as $$
declare
  target_date date := coalesce((open_payload->>'business_date')::date, current_date);
  target_opening numeric := (open_payload->>'opening_cash')::numeric;
  target_actor text := open_payload->>'opened_by';
begin
  if target_opening is null or target_opening < 0 or target_actor is null or btrim(target_actor) = '' then raise exception 'Invalid opening'; end if;
  insert into public.cash_register_days (business_date, opening_cash, opened_by)
  values (target_date, target_opening, target_actor)
  on conflict on constraint cash_register_days_pkey do nothing;
  if not found then raise exception 'Business day is already open or closed'; end if;
  insert into public.cashier_audit_logs (event_type, entity_type, actor, details)
  values ('daily_open', 'cash_register_day', target_actor, jsonb_build_object('business_date', target_date, 'opening_cash', target_opening));
  business_date := target_date; opening_cash := target_opening; return next;
end;
$$;

