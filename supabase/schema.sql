        'total', oi.total_price,
        'notes', oi.notes,
        'sort_order', oi.sort_order
      )
      order by oi.sort_order, oi.created_at
    ) filter (where oi.id is not null),
    '[]'::json
  ) as items
from public.orders o
left join public.order_items oi on oi.order_id = o.id
group by o.id;
