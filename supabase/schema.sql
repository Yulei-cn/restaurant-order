create or replace function public.assign_payment_event_hash()
returns trigger
language plpgsql
as $$
declare
  prior_hash text;
begin
  -- Serialise the hash chain when multiple iPads submit a payment simultaneously.
  perform pg_advisory_xact_lock(hashtext('cube_payment_event_chain'));

  select event_hash into prior_hash
  from public.payment_events
  order by fiscal_sequence desc
  limit 1;

  new.previous_event_hash := prior_hash;
  new.event_hash := encode(
    digest(
      concat_ws('|', new.fiscal_sequence::text, new.order_id::text, new.event_type,
        new.payment_method, new.amount::text, new.currency,
        coalesce(new.terminal_reference, ''), coalesce(new.reason, ''),
        new.recorded_by, new.recorded_at::text, coalesce(prior_hash, '')),
      'sha256'
    ),
    'hex'
  );
  return new;
end;
$$;

create or replace function public.prevent_financial_record_change()
returns trigger
language plpgsql
as $$
begin
  raise exception 'Financial records are append-only; create a reversal or refund event instead';
end;
$$;

create or replace function public.require_open_cash_register_day()
returns trigger
language plpgsql
as $$
begin
  if not exists (
    select 1 from public.cash_register_days as cash_day
    where cash_day.business_date = current_date and cash_day.status = 'open'
  ) then
    raise exception 'Cash register is not open for today';
  end if;
  return new;
end;
$$;

